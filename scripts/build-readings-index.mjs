// Writes src/data/readings-index.js: the few fields the home page needs (id, title, level, listening) so the full
// texts (src/data/readings.js) can load lazily. Run after editing readings.js; a content test fails if it is stale.
import { writeFileSync } from 'node:fs';
import { readings } from '../src/data/readings.js';

const rows = readings.map(({ id, title, level, listening }) => [id, title, level, !!listening]);
writeFileSync(new URL('../src/data/readings-index.js', import.meta.url), `// Generated by scripts/build-readings-index.mjs — do not edit.
export const readingsIndex = ${JSON.stringify(rows)}.map(([id, title, level, listening]) => ({ id, title, level, listening }));
`);
console.log(`${rows.length} texts indexed`);
