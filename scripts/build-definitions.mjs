// Builds src/data/definitions.js: English learner definitions for every word used in Nextgen content.
// Source: Open English WordNet rows of CloudBytes-Academy/English-Dictionary-Open-Source v2
// (CC BY 4.0 — see DATA-LICENSES.md). Usage:
//   node scripts/build-definitions.mjs /path/to/dictionary.jsonl.gz
import { createReadStream, writeFileSync } from 'node:fs';
import { createGunzip } from 'node:zlib';
import { createInterface } from 'node:readline';
import { lemmaCandidates } from '../src/core/dictionary.js';
import { vocabulary } from '../src/data/vocabulary.js';
import { readings } from '../src/data/readings.js';
import { grammar } from '../src/data/grammar.js';
import { scenarios } from '../src/data/dialogues.js';
import { exams } from '../src/data/exams.js';
import { readingBank } from '../src/data/ielts-bank-reading.js';
import { listeningBank } from '../src/data/ielts-bank-listening.js';

const MAX_SENSES = 2;
const SKIP = new Set('a an the of to and or but is are was were be been am i you he she it we they me him her us them my your his its our their this that these those in on at for with by from as if so not no do does did has have had will would can could shall should may might must there here what who which when where why how than then also very too just'.split(' '));

const text = [
  ...vocabulary.flatMap((v) => [v.word, v.example]),
  ...[...readings, ...readingBank, ...listeningBank].flatMap((r) => [r.text, ...r.questions.map((q) => q.prompt)]),
  ...grammar.flatMap((t) => [...t.examples, ...t.exercises.map((e) => e.prompt)]),
  ...scenarios.flatMap((s) => s.lines),
  ...exams.flatMap((e) => e.questions.map((q) => q.prompt)),
].join(' ');

const wanted = new Set(vocabulary.map((v) => v.word.toLowerCase()));
for (const w of text.toLowerCase().replace(/[’]/g, "'").match(/[a-z][a-z'-]*/g) ?? []) {
  const word = w.replace(/'s$/, '').replace(/^'+|'+$/g, '');
  if (word.length > 2 && !SKIP.has(word)) lemmaCandidates(word).forEach((c) => wanted.add(c));
}

const senses = new Map();
const input = createInterface({ input: createReadStream(process.argv[2]).pipe(createGunzip()) });
for await (const line of input) {
  const row = JSON.parse(line);
  const word = row.word;
  // Capitalized rows are proper nouns ("Book" = the Koran, "Light" = Quaker doctrine), not learner senses.
  if (row.source !== 'oewn' || word !== word.toLowerCase() || !wanted.has(word)) continue;
  if (!senses.has(word)) senses.set(word, []);
  senses.get(word).push([row.pos, row.definition, row.examples[0] ?? '']);
}

// WordNet lists senses most-common-first within each part of speech, but not across them.
// POS order: the vocabulary card's POS ("run" → verb, not baseball), else the POS with most senses
// ("shrink" → verb, not psychiatrist). Take the top sense of each POS first, then the rest.
const vocabPos = new Map(vocabulary.map((v) => [v.word.toLowerCase(), v.pos === 'phrasal verb' ? 'verb' : v.pos]));
const out = {};
for (const [word, list] of [...senses].sort(([a], [b]) => (a < b ? -1 : 1))) {
  const groups = Map.groupBy([...new Map(list.map((s) => [s[1], s])).values()], (s) => s[0]);
  const pos = vocabPos.get(word);
  const order = [...groups.keys()].sort((a, b) => (b === pos) - (a === pos) || groups.get(b).length - groups.get(a).length);
  const firsts = order.map((p) => groups.get(p)[0]);
  out[word] = [...firsts, ...order.flatMap((p) => groups.get(p).slice(1))].slice(0, MAX_SENSES);
}

writeFileSync(new URL('../src/data/definitions.js', import.meta.url),
  `// Generated by scripts/build-definitions.mjs — do not edit by hand.\n` +
  `// Definitions adapted from Open English WordNet (CC BY 4.0), via CloudBytes-Academy/English-Dictionary-Open-Source. See DATA-LICENSES.md.\n` +
  `// word -> [[part of speech, definition, example], ...]\n` +
  `export const definitions = ${JSON.stringify(out)};\n`);
console.log(`${Object.keys(out).length} words with definitions (wanted ${wanted.size})`);
